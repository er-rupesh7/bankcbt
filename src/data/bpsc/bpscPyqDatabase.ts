// Helper: Query PYQ Database with filters
export interface PYQFilterOptions {
  treVersion?: BPSCTREVersion;
  shift?: string;
  section?: 'LANGUAGE' | 'GENERAL_STUDIES' | 'SUBJECT_CORE';
  unit?: string;
  difficulty?: 'EASY' | 'MODERATE' | 'HARD';
  verificationStatus?: BPSCVerificationStatus;
  searchTerm?: string;
}

export function queryBPSCPYQs(filters?: PYQFilterOptions): BPSCQuestionMetadata[] {
  return AUTHENTIC_BPSC_PYQ_DATABASE.filter((q) => {
    if (filters?.treVersion && q.treVersion !== filters.treVersion) return false;
    if (filters?.shift && q.shift !== filters.shift) return false;
    if (filters?.section && q.section !== filters.section) return false;
    if (filters?.unit && q.unit !== filters.unit) return false;
    if (filters?.difficulty && q.difficulty !== filters.difficulty) return false;
    if (filters?.verificationStatus && q.verificationStatus !== filters.verificationStatus) return false;
    if (filters?.searchTerm) {
      const term = filters.searchTerm.toLowerCase();
      const matchEn = q.questionTextEn.toLowerCase().includes(term);
      const matchHi = q.questionTextHi.toLowerCase().includes(term);
      const matchTopic = q.topic.toLowerCase().includes(term);
      if (!matchEn && !matchHi && !matchTopic) return false;
    }
    return true;
  });
}

// Summary Statistics for PYQ Database
export function getPYQDatabaseStats() {
  const total = AUTHENTIC_BPSC_PYQ_DATABASE.length;
  const tre1Count = AUTHENTIC_BPSC_PYQ_DATABASE.filter((q) => q.treVersion === 'TRE_1_0').length;
  const tre2Count = AUTHENTIC_BPSC_PYQ_DATABASE.filter((q) => q.treVersion === 'TRE_2_0').length;
  const tre3Count = AUTHENTIC_BPSC_PYQ_DATABASE.filter((q) => q.treVersion === 'TRE_3_0').length;
  const verifiedCount = AUTHENTIC_BPSC_PYQ_DATABASE.filter((q) => q.verificationStatus === 'OFFICIALLY_VERIFIED').length;

  return {
    totalQuestions: total,
    byVersion: {
      TRE_1_0: tre1Count,
      TRE_2_0: tre2Count,
      TRE_3_0: tre3Count,
    },
    verificationRate: Math.round((verifiedCount / total) * 100),
    officiallyVerifiedCount: verifiedCount,
  };
}
